#!/usr/bin/env python3
"""Render catalog views; --check reports drift without changing files."""

from __future__ import annotations

import argparse
import sys
from html import escape
from pathlib import Path
from urllib.parse import quote

from catalog import CATEGORIES, FEATURED_IDS, ROOT, load_benchmarks, load_catalog, markdown_text, recent_papers, sorted_papers


NOTICE = "<!-- Generated by scripts/render.py from data/. Edit the catalog, then regenerate. -->\n"


def cell_text(value):
    """Keep catalog text inside one table cell, including future multiline entries."""
    return (escape(str(value)).replace("|", "&#124;").replace("\r\n", "\n")
            .replace("\r", "\n").replace("\n", "<br>"))


def cell_link(label, url):
    target = quote(url, safe="/:#?&=@%+-._~")
    return f"[{markdown_text(cell_text(label))}]({target})"


def notes(item, include_artifacts=False):
    """Use HTML inside details so GitHub renders notes reliably within table cells."""
    parts = []
    if include_artifacts and item.get("artifact_status"):
        parts.append(cell_text(item["artifact_status"]))
    if item.get("topics"):
        parts.append("<strong>Topics:</strong> " + cell_text(", ".join(item["topics"])))
    sources = " · ".join(
        f'<a href="{escape(quote(url, safe="/:#?&=@%+-._~"), quote=True)}">Source {index}</a>'
        for index, url in enumerate(item["evidence"], 1))
    parts.extend(["<strong>Sources:</strong> " + sources,
                  "<strong>Content checked:</strong> " + cell_text(item["checked_on"])])
    label = "Release notes and sources" if include_artifacts else "Sources and check date"
    return f"<details><summary>{label}</summary>" + "<br><br>".join(parts) + "</details>"


def paper_entry(item, compact=False):
    links = []
    for field, name in (("code_url", "Code"), ("dataset_url", "Data")):
        if item.get(field):
            links.append(cell_link(name, item[field]))
    anchor = "" if compact else f'<a id="{item["id"]}"></a>'
    target = f"papers/README.md#{item['id']}" if compact else item["primary_url"]
    paper = (anchor + cell_link(item["title"], target)
             + "<br>" + cell_text(item["publication_status"])
             + "<br><em>" + cell_text(item["scope"]) + "</em>")
    artifacts = (" · ".join(links) if links else "Release not verified")
    artifacts += "<br>" + (cell_link("Details", target) if compact else notes(item, include_artifacts=True))
    return "| " + " | ".join([str(item["year"]), paper, cell_text(item["summary"]), artifacts]) + " |"


def resource_entry(item, papers):
    resource = f'<a id="{item["id"]}"></a>' + cell_link(item["name"], item["url"])
    if item["kind"] != "dataset":
        resource += "<br><em>" + cell_text(item["kind"]) + "</em>"
    purpose = cell_text(item["description"]) + "<br><br>" + cell_text(item["protocol"])
    availability = cell_text(item["availability"]) + "<br><br><strong>License:</strong> " + cell_text(item["license_note"])
    links = [cell_link("Resource", item["url"])]
    if item["paper_ids"]:
        multiple = len(item["paper_ids"]) > 1
        for index, identifier in enumerate(item["paper_ids"], 1):
            papers[identifier]  # Fail early for broken catalog references.
            links.append(cell_link(f"Paper {index}" if multiple else "Paper", f"../papers/README.md#{identifier}"))
    link_cell = "<br>".join(links) + "<br>" + notes(item)
    return "| " + " | ".join([resource, purpose, availability, link_cell]) + " |"


def table(headers, rows):
    return "\n".join(["| " + " | ".join(headers) + " |",
                      "| " + " | ".join("---" for _ in headers) + " |", *rows])


def year_groups(items, year_for):
    groups = {}
    for item in items:
        groups.setdefault(year_for(item), []).append(item)
    return [(year, groups[year]) for year in sorted(groups, key=lambda year: (year is None, -(year or 0)))]


def papers_by_year(records):
    groups = year_groups(sorted_papers(records), lambda item: item["year"])
    lines = [NOTICE, "# Papers by year", "",
             "[Overview](../README.md) · [Browse by topic](README.md)", "",
             "Newest publication years first. Years follow the catalog: the verified venue year when available, otherwise the recorded preprint year.", "",
             "## Jump to a year", "",
             " · ".join(f"[{year} ({len(items)})](#year-{year})" for year, items in groups), ""]
    for year, items in groups:
        lines.extend([f'<a id="year-{year}"></a>', f"## {year}", "",
                      table(["Year", "Paper / venue", "Concise summary", "Code / data"],
                            [paper_entry(item) for item in items]), ""])
    return "\n".join(lines).rstrip() + "\n"


BENCHMARK_LABELS = {
    "yes": "Yes", "not_targeted": "Not targeted", "not_reported": "Not reported",
    "generated": "Generated", "supplied": "Supplied", "mixed": "Mixed",
    "static": "Static", "recorded": "Recorded", "simulated": "Simulated",
    "public_artifacts": "Public artifacts", "author_download": "Author download",
    "release_unverified": "Release unverified",
}


def comparison_cell(value):
    status = value.get("status", value.get("mode"))
    return "<strong>" + BENCHMARK_LABELS[status] + "</strong><br>" + cell_text(value["detail"])


def benchmark_sources(item):
    parts = []
    for index, source in enumerate(item["evidence"], 1):
        url = escape(quote(source["url"], safe="/:#?&=@%+-._~"), quote=True)
        fields = ", ".join(field.replace("_", " ") for field in source["supports"])
        parts.append(f'<a href="{url}">Source {index}</a> (' + cell_text(fields) + "): " + cell_text(source["locator"]))
    parts.append("<strong>Checked:</strong> " + cell_text(item["checked_on"]))
    return "<details><summary>Sources</summary>" + "<br><br>".join(parts) + "</details>"


def benchmark_matrix(root, resources):
    records = sorted(load_benchmarks(root), key=lambda item: (item["relevance"] != "direct", item["label"].casefold()))
    datasets = {item["id"]: item for item in resources if item["kind"] == "dataset"}
    coverage, protocols = [], []
    for item in records:
        identifier = item["resource_id"]
        resource = datasets[identifier]
        target = f"../datasets/README.md#{identifier}"
        name = (f'<a id="{identifier}"></a>' + cell_link(item["label"], target)
                + "<br><em>" + cell_text(item["relevance"]) + "</em><br>" + benchmark_sources(item))
        coverage.append("| " + " | ".join([name, comparison_cell(item["ambiguity"]),
                                              comparison_cell(item["unanswerability"]),
                                              comparison_cell(item["clarification"]), cell_text(item["domain"])]) + " |")
        access = ("<strong>" + BENCHMARK_LABELS[item["data_access"]] + "</strong><br>"
                  + cell_link("Official resource", resource["url"])
                  + "<br><details><summary>Access details</summary>" + cell_text(resource["availability"])
                  + "<br><br><strong>License / terms:</strong> " + cell_text(resource["license_note"])
                  + f'<br><br><a href="{escape(target, quote=True)}">Full resource record</a></details>')
        protocols.append("| " + " | ".join([cell_link(item["label"], f"#{identifier}"),
                                               comparison_cell(item["interaction"]),
                                               cell_text(item["evaluation"]), access]) + " |")
    template = (root / "docs" / "benchmark-matrix.template.md").read_text(encoding="utf-8")
    substitutions = {"BENCHMARK_COUNT": str(len(records)),
                     "COVERAGE_TABLE": table(["Benchmark", "Ambiguity", "Unanswerability", "Clarification", "Domain"], coverage),
                     "PROTOCOL_TABLE": table(["Benchmark", "Evaluation interaction", "What is measured", "Data access"], protocols),
                     "UPDATED": max(item["checked_on"] for item in records)}
    for key, value in substitutions.items():
        template = template.replace("{{" + key + "}}", value)
    return NOTICE + template.rstrip() + "\n"


def outputs(root=ROOT):
    records, resources, meta = load_catalog(root)
    by_id = {item["id"]: item for item in records}
    papers = [NOTICE, "# Papers", "", "[Back to the overview](../README.md) · [Browse by year](by-year.md)", "",
              "Annotations describe published evidence and its limits. Source checks do not establish independent reproduction.", "",
              "Expand **Release notes and sources** for artifact qualifications and provenance. "
              "**Release not verified** means no code or data link was confirmed, not that no release exists.", ""]
    present = {item["category"] for item in records}
    papers.extend(["## Contents", "", "\n".join(f"- [{heading}](#{category})" for category, heading in CATEGORIES.items() if category in present), ""])
    for category, heading in CATEGORIES.items():
        selected = sorted_papers([item for item in records if item["category"] == category])
        if selected:
            papers.extend([f'<a id="{category}"></a>', f"## {heading}", "",
                           table(["Year", "Paper / venue", "Concise summary", "Code / data"],
                                 [paper_entry(item) for item in selected]), ""])
    result = {Path("papers/README.md"): "\n".join(papers).rstrip() + "\n"}
    result[Path("papers/by-year.md")] = papers_by_year(records)
    for folder, heading, kinds in (("systems", "Systems and tools", {"system", "tool"}),
                                  ("datasets", "Datasets and benchmarks", {"dataset"})):
        chosen = sorted((item for item in resources if item["kind"] in kinds), key=lambda item: item["name"].casefold())
        headers = (["Dataset", "Task / protocol", "Access and license", "Links"] if folder == "datasets"
                   else ["System / tool", "Purpose", "Availability", "Links"])
        lines = [NOTICE, f"# {heading}", "", "[Back to the overview](../README.md)", "",
                 "Availability and licenses are source-specific. A linked paper, project, or dataset is not evidence of independent replication.", "",
                 "## Contents", "", "\n".join(f"- [{markdown_text(item['name'])}](#{item['id']})" for item in chosen), "",
                 table(headers, [resource_entry(item, by_id) for item in chosen])]
        if folder == "datasets":
            groups = year_groups(chosen, lambda item: max((by_id[identifier]["year"] for identifier in item["paper_ids"]), default=None))
            contents, sections = [], []
            for year, items in groups:
                anchor = f"year-{year}" if year is not None else "no-linked-paper"
                label = str(year) if year is not None else "No linked paper"
                contents.append(f"- [{label} ({len(items)})](#{anchor})")
                sections.extend([f'<a id="{anchor}"></a>', f"### {label}", "",
                                 table(headers, [resource_entry(item, by_id) for item in items]), ""])
            template = (root / folder / "README.template.md").read_text(encoding="utf-8")
            template = template.replace("{{DATASET_CONTENTS}}", "\n".join(contents))
            template = template.replace("{{DATASET_TABLE}}", "\n".join(sections).rstrip())
            result[Path(folder) / "README.md"] = NOTICE + template.rstrip() + "\n"
        else:
            result[Path(folder) / "README.md"] = "\n".join(lines).rstrip() + "\n"
    result[Path("docs/benchmark-matrix.md")] = benchmark_matrix(root, resources)
    template = (root / "docs" / "README.template.md").read_text(encoding="utf-8")
    missing = [identifier for identifier in FEATURED_IDS if identifier not in by_id]
    if missing:
        raise ValueError("Missing featured paper IDs: " + ", ".join(missing))
    replacements = {
        "PAPER_COUNT": str(len(records)),
        "CORE_COUNT": str(sum(item["scope"] == "core" for item in records)),
        "SYSTEM_COUNT": str(sum(item["kind"] in {"system", "tool"} for item in resources)),
        "DATASET_COUNT": str(sum(item["kind"] == "dataset" for item in resources)),
        "UPDATED": meta["updated"],
        "START_HERE": table(["Year", "Paper / venue", "Concise summary", "Code / data"],
                            [paper_entry(by_id[identifier], compact=True) for identifier in FEATURED_IDS]),
        "RECENT": table(["Year", "Paper / venue", "Concise summary", "Code / data"],
                        [paper_entry(item, compact=True) for item in recent_papers(records)[:8]]),
    }
    for key, value in replacements.items():
        template = template.replace("{{" + key + "}}", value)
    import re
    if re.search(r"\{\{[A-Z_]+\}\}", template):
        raise ValueError("Unresolved README template placeholder")
    result[Path("README.md")] = NOTICE + template.rstrip() + "\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated views are stale")
    arguments = parser.parse_args()
    try:
        rendered = outputs()
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Render failed: {error}", file=sys.stderr)
        return 1
    stale = []
    for path, content in rendered.items():
        target = ROOT / path
        if arguments.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(path))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
    if stale:
        print("Stale generated views: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if arguments.check else 'Rendered'} {len(rendered)} catalog views.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
